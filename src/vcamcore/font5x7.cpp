const char* const* FindGlyph(char c) {
  if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
  for (const Glyph& g : kGlyphs) {
    if (g.c == c) return g.rows;
  }
  return nullptr;
}

